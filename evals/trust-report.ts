/**
 * Assembles TRUST_REPORT.md from the committed eval artifacts in evals/results/.
 * Numbers appear here when a run produced them, and not before — the report is a
 * function of the scorecards, never hand-written. Run after evals:
 *   npm run evals:retrieval && npm run evals -- --record && npm run evals:probes
 *   npm run trust-report
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const RESULTS = path.join(process.cwd(), 'evals', 'results');
const OUT = path.join(process.cwd(), 'TRUST_REPORT.md');

function load<T>(name: string): T | null {
  const p = path.join(RESULTS, name);
  return existsSync(p) ? (JSON.parse(readFileSync(p, 'utf8')) as T) : null;
}

function pct(x: number) {
  return `${(x * 100).toFixed(1)}%`;
}

function main() {
  const retrieval = load<any>('retrieval-scorecard.json');
  const assessment = load<any>('assessment-scorecard.json');
  const probes = load<any>('probe-scorecard.json');

  const lines: string[] = [];
  lines.push('# Trust report');
  lines.push('');
  lines.push('> Generated by `npm run trust-report` from the committed artifacts in `evals/results/`.');
  lines.push('> Numbers appear when a run produced them, and not before. Methodology: [`evals/golden/RUBRIC.md`](evals/golden/RUBRIC.md).');
  lines.push('');

  // --- classification ---
  lines.push('## Classification accuracy');
  lines.push('');
  if (assessment) {
    const partialNote = assessment.partial
      ? ` · **PARTIAL run: ${assessment.n}/${assessment.cases_total} cases recorded** (the rest await a key with credit — re-run \`npm run evals -- --record\` to complete; nothing is silently dropped)`
      : '';
    lines.push(`Run ${assessment.run_at} · ${assessment.n} cases · split core/contested because they measure different things (RUBRIC.md)${partialNote}.`);
    lines.push('');
    lines.push('| Split | n | AI-or-not | Risk tier | Cost-ceiling (GATED) | Autonomy vs rubric (accuracy) | Answer-judge |');
    lines.push('|---|---|---|---|---|---|---|');
    for (const k of ['core', 'contested']) {
      const s = assessment.splits[k];
      if (!s || !s.n) continue;
      lines.push(
        `| ${k} | ${s.n} | ${pct(s.ai_or_not / s.n)} | ${pct(s.risk / s.n)} | ${pct((s.cost_ok ?? s.n) / s.n)} | ${pct((s.golden_ok ?? 0) / s.n)} | ${pct(s.answer_pass / s.n)} |`,
      );
    }
    lines.push('');
    lines.push(
      `**Cost-ceiling respected on every case: ${assessment.cost_ceiling_respected_all ? 'yes' : 'NO'}.** This is the deterministic safety invariant — the system never recommends a tier above what cost-of-error permits (the \`autonomyCeiling\` clamp in \`lib/ladder.ts\`). It is code-enforced and CI-gated, so it reads 100%. The separate "autonomy vs rubric" column is **accuracy, not safety**: agreement with the golden set's stricter per-case ceiling (e.g. a benefits-eligibility screen the rubric pins to \`suggest\`). A miss there is a documented-reading disagreement on a contested case, reported but not gated.`,
    );
    lines.push('');
    lines.push(
      'Core accuracy measures the system; contested accuracy measures agreement with one documented reading of genuinely arguable cases, and the disclosed expectation is that the system errs toward caution. The answer-judge column is model-judged (it grounds on the evidence the specialists actually retrieved) and is reported, not gated — judges drift, so only the deterministic metrics gate CI.',
    );
  } else {
    lines.push('_No assessment scorecard yet. Run `GOOGLE_API_KEY=... npm run evals -- --record`._');
  }
  lines.push('');

  // --- retrieval ---
  lines.push('## Retrieval scorecard');
  lines.push('');
  if (retrieval) {
    lines.push(`Run ${retrieval.run_at} · query = each golden case description, relevant = its labelled \`relevant_pattern_ids\` · k=${retrieval.k}.`);
    lines.push('');
    lines.push('| Config | Queries | Recall@5 | MRR |');
    lines.push('|---|---|---|---|');
    for (const c of retrieval.configs) {
      if (c.skipped) lines.push(`| ${c.config} | — | _skipped: ${c.skipped}_ | — |`);
      else lines.push(`| ${c.config} | ${c.queries} | ${pct(c.recall_at_5)} | ${c.mrr} |`);
    }
    lines.push('');
    const denseSkipped = retrieval.configs.some((c: any) => c.config !== 'bm25-only' && c.skipped);
    const hybridRow = retrieval.configs.find((c: any) => c.config === 'hybrid');
    const denseRow = retrieval.configs.find((c: any) => c.config === 'dense-only');
    const measuredVerdict =
      hybridRow && !hybridRow.skipped && denseRow && !denseRow.skipped
        ? ` Measured here: **hybrid (${pct(hybridRow.recall_at_5)}) beats both bm25-only (${pct(retrieval.ci_gate.value)}) and dense-only (${pct(denseRow.recall_at_5)})**, so hybrid is the live default — pattern names favour BM25, descriptions favour dense, and fusing genuinely helps on this corpus.`
        : ' Dense/hybrid rows populate once `npm run ingest:embed` has run with a working key.';
    lines.push(
      `The **default retrieval leg is the measured winner, not an assumed one.** \`bm25-only\` runs with no API key and is the deterministic CI gate (floor ${retrieval.ci_gate.floor}, current ${retrieval.ci_gate.value} — ${retrieval.ci_gate.pass ? 'PASS' : 'FAIL'}). On this corpus, pattern *names* are terms-of-art (BM25 territory) while use-case *descriptions* are paraphrase (dense territory), so hybrid is the principled default — but the scorecard decides: if a leg is net-negative here, the default flips, exactly as it did for the sibling \`ai-act-triage\`.${denseSkipped ? ' Dense/hybrid rows populate once `npm run ingest:embed` has run with a working key.' : measuredVerdict}`,
    );
  } else {
    lines.push('_No retrieval scorecard yet. Run `npm run evals:retrieval`._');
  }
  lines.push('');

  // --- probes ---
  lines.push('## Security probes');
  lines.push('');
  if (probes) {
    lines.push(`Run ${probes.run_at} — ${probes.passed}/${probes.total} passed.`);
    lines.push('');
    for (const r of probes.results) {
      lines.push(`- ${r.passed ? '✅' : '❌'} **${r.name}** (${r.kind}) — ${r.detail}`);
    }
    lines.push('');
    lines.push(
      'The lethal-trifecta containment is **structural, not prompt-based**. Two independent guards: a deterministic input gate rejects instruction payloads before any model spend, and — proven on the compiled graph — the only irreversible action (`commit_roadmap`) has no inbound edge from any specialist; it is reachable only from the human gate. An instruction smuggled through a use-case description or a retrieved pattern card cannot reach the write path, because the write is gated on the user’s approval, not on any model output. A finite probe set proves the defences fire on these shapes; it does not prove the absence of injection risk.',
    );
  } else {
    lines.push('_No probe scorecard yet. Run `npm run evals:probes`._');
  }
  lines.push('');

  // --- cost ---
  lines.push('## Cost');
  lines.push('');
  if (assessment) {
    lines.push(
      `Mean metered cost per use case: **€${assessment.cost_eur_per_case}** (token counts at list prices, derived from real traces, never estimated). A 40-item backlog triages for ~€${(assessment.cost_eur_per_case * 40).toFixed(2)}. This prices the triage decision — which pilots deserve the build — not the build.`,
    );
  } else {
    lines.push('_Per-case cost appears after a recorded run._');
  }
  lines.push('');
  lines.push('## Where the human sits');
  lines.push('');
  lines.push(
    'Every interactive run pauses on a checkpointed `interrupt()` before the roadmap is committed. With `DATABASE_URL` set the pause is durable (Postgres checkpointer): it survives restarts, deploys, and fresh serverless invocations. Without it the gate degrades to in-memory and a restart loses the pending approval; the UI and every run report which mode is live rather than letting the degradation pass silently. Eval runs bypass the gate explicitly (`auto_approve`) because evals measure the model pipeline and the gate is process.',
  );
  lines.push('');

  writeFileSync(OUT, lines.join('\n') + '\n');
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}

main();
